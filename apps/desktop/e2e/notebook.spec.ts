import { test, expect } from '@playwright/test';
import path from 'node:path';
import { readFile } from 'node:fs/promises';

const base = 'http://127.0.0.1:8765/api/v1';
const headers = { Authorization: 'Bearer dev-token' };

test('notebook creation, guarded editing, conflict resolution, search, export and delete recovery', async ({ page, request }, info) => {
  const stamp = `Notebook ${Date.now()}`;
  const imported = await request.post(`${base}/papers/import-paths`, { headers, data: { paths: [path.resolve('../../tests/fixtures/academic.pdf')] } });
  expect(imported.ok()).toBeTruthy();
  const batch = await imported.json();
  const item = batch.items[0] || batch.duplicates[0];
  const paper = await (await request.get(`${base}/papers/${item.id}`, { headers })).json();
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: '笔记与书签', exact: true }).click();
  await expect(page.getByRole('heading', { name: '笔记与书签' })).toBeVisible();
  await page.getByRole('button', { name: '新建笔记', exact: true }).first().click();
  const creating = page.getByRole('dialog', { name: '新建笔记', exact: true });
  await creating.getByRole('combobox', { name: '选择来源论文' }).fill(paper.filename);
  await creating.getByRole('option').filter({ hasText: paper.title || paper.filename }).first().click();
  await creating.getByLabel('笔记标题', { exact: true }).fill(stamp);
  await creating.getByLabel('笔记内容', { exact: true }).fill('研究证据 Δ consistency <script>literal</script>');
  await creating.getByLabel('笔记标签', { exact: true }).fill('回归验证, 证据');
  await creating.getByRole('button', { name: '蓝色', exact: true }).click();
  await creating.getByRole('button', { name: '关闭对话框' }).click();
  const guard = page.getByRole('dialog', { name: '有未保存的修改' });
  await expect(guard).toBeVisible();
  await guard.getByRole('button', { name: '继续编辑', exact: true }).click();
  await expect(creating.getByLabel('笔记内容', { exact: true })).toHaveValue('研究证据 Δ consistency <script>literal</script>');
  const createdResponse = page.waitForResponse(response => response.url().endsWith(`/papers/${paper.id}/annotations`) && response.request().method() === 'POST');
  await creating.getByRole('button', { name: '保存笔记', exact: true }).click();
  const created = await createdResponse; expect(created.ok(), await created.text()).toBeTruthy();
  let annotation = await created.json();
  const editor = page.getByRole('dialog', { name: '编辑笔记', exact: true });
  await expect(editor).toBeVisible();
  await expect(editor.getByRole('button', { name: '保存笔记', exact: true })).toBeDisabled();
  expect(annotation.color).toBe('blue');
  expect(annotation.tags).toEqual(['回归验证', '证据']);

  await editor.getByLabel('笔记内容', { exact: true }).fill('我的未保存修正');
  const remote = await request.patch(`${base}/annotations/${annotation.id}`, { headers, data: { expected_version: annotation.version, body: '另一处保存的新内容' } });
  expect(remote.ok()).toBeTruthy();
  await editor.getByRole('button', { name: '保存笔记', exact: true }).click();
  await expect(editor.getByText('这条笔记已在其他位置更新，当前编辑内容仍保留。')).toBeVisible();
  await expect(editor.getByLabel('笔记内容', { exact: true })).toHaveValue('我的未保存修正');
  await editor.getByRole('button', { name: '载入最新记录', exact: true }).click();
  await expect(editor.getByLabel('笔记内容', { exact: true })).toHaveValue('另一处保存的新内容');
  await editor.getByLabel('笔记内容', { exact: true }).fill('最终研究证据 Δ consistency <script>literal</script>');
  await page.keyboard.press('Control+s');
  await expect(editor.getByRole('button', { name: '保存笔记', exact: true })).toBeDisabled();
  annotation = await (await request.get(`${base}/annotations/${annotation.id}`, { headers })).json();
  expect(annotation.body).toBe('最终研究证据 Δ consistency <script>literal</script>');
  await editor.getByRole('button', { name: '关闭对话框' }).click();
  await expect(editor).not.toBeVisible();
  await page.getByLabel('搜索笔记', { exact: true }).fill(stamp);
  await expect(page.locator('.annotation-row')).toHaveCount(1);
  await expect(page.locator('.annotation-open')).toContainText('<script>literal</script>');
  await page.screenshot({ path: info.outputPath('notebook-actual.png') });

  await page.getByRole('button', { name: '导出', exact: true }).click();
  const exporting = page.getByRole('dialog', { name: '导出笔记', exact: true });
  await exporting.getByLabel('笔记导出格式', { exact: true }).selectOption('json');
  const downloadPromise = page.waitForEvent('download');
  await exporting.getByRole('button', { name: '导出笔记', exact: true }).click();
  const download = await downloadPromise;
  const destination = info.outputPath('notebook-export.json'); await download.saveAs(destination);
  const document = JSON.parse(await readFile(destination, 'utf-8'));
  expect(JSON.stringify(document)).toContain(annotation.id);
  expect(JSON.stringify(document)).toContain(paper.id);
  expect(JSON.stringify(document)).toContain('最终研究证据');

  await page.keyboard.press('Control+k');
  await page.getByLabel('全局全文搜索', { exact: true }).fill(stamp);
  const noteGroup = page.locator('.search-group').filter({ has: page.getByRole('heading', { name: /^笔记/ }) });
  await expect(noteGroup.locator('.search-result')).toHaveCount(1);
  await noteGroup.locator('.search-result').click();
  await expect(page.getByRole('tab', { name: /^笔记 \d/ })).toHaveAttribute('aria-selected', 'true');
  await expect(page.locator('.paper-side').getByLabel('笔记标题', { exact: true })).toHaveValue(stamp);
  await expect(page.locator('.pdf-page canvas').first()).toBeVisible();
  await page.getByRole('button', { name: '笔记与书签', exact: true }).click();
  await expect(page.getByLabel('搜索笔记', { exact: true })).toHaveValue(stamp);
  await expect(page.locator('.annotation-row')).toHaveCount(1);
  await page.getByRole('button', { name: `删除笔记 ${stamp}`, exact: true }).click();
  const deleting = page.getByRole('dialog', { name: '删除笔记', exact: true });
  await deleting.getByRole('button', { name: '删除笔记', exact: true }).click();
  await expect(page.locator('.annotation-row')).toHaveCount(0);
  await page.getByRole('button', { name: '查看已删除笔记', exact: true }).click();
  await expect(page.getByLabel('搜索笔记', { exact: true })).toBeDisabled();
  const removed = page.locator('.annotation-row').filter({ hasText: stamp });
  await expect(removed).toBeVisible();
  await removed.getByRole('button', { name: '恢复', exact: true }).click();
  await page.getByRole('button', { name: '返回全部笔记', exact: true }).click();
  await expect(page.getByLabel('搜索笔记', { exact: true })).toHaveValue(stamp);
  await expect(page.locator('.annotation-row')).toHaveCount(1);
  expect(errors).toEqual([]);
});

test('a prefilled region note cannot disappear on closing without a decision', async ({ page, request }) => {
  const papers = await (await request.get(`${base}/papers?limit=200`, { headers })).json();
  const paper = papers.items.find((item: { filename: string }) => item.filename === 'academic.pdf');
  expect(paper).toBeTruthy();
  await page.goto('/');
  await page.getByRole('button', { name: '论文库', exact: true }).click();
  await page.getByLabel('搜索论文', { exact: true }).fill(paper.filename);
  await page.locator('.paper-primary').first().click();
  await page.getByLabel('页面适应方式', { exact: true }).selectOption('page');
  await page.getByRole('button', { name: '框选区域笔记', exact: true }).click();
  const bounds = await page.locator('.pdf-page').first().boundingBox();
  expect(bounds).toBeTruthy();
  await page.mouse.move(bounds!.x + 30, bounds!.y + 45); await page.mouse.down();
  await page.mouse.move(bounds!.x + 150, bounds!.y + 95); await page.mouse.up();
  const modal = page.getByRole('dialog', { name: '区域笔记', exact: true });
  await expect(modal).toBeVisible();
  await modal.getByRole('button', { name: '关闭对话框', exact: true }).click();
  const guard = page.getByRole('dialog', { name: '有未保存的修改' });
  await expect(guard).toBeVisible();
  await guard.getByRole('button', { name: '继续编辑', exact: true }).click();
  await expect(modal).toBeVisible();
  await modal.getByRole('button', { name: '关闭对话框', exact: true }).click();
  await guard.getByRole('button', { name: '放弃修改', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
});
