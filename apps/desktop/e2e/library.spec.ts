import { test, expect } from '@playwright/test';
import path from 'node:path';

const library = process.env.PAPERVAULT_E2E_LIBRARY || path.resolve('../../.test-data/ui-library');
const fixture = process.env.PAPERVAULT_E2E_PDF || path.resolve('../../tests/fixtures/academic.pdf');
const apiUrl = process.env.PAPERVAULT_E2E_API_URL || 'http://127.0.0.1:8765/api/v1';
const headers = { Authorization: `Bearer ${process.env.PAPERVAULT_E2E_TOKEN || 'dev-token'}` };

test('real local library import, PDF selection, caption search, export and reload', async ({ page, request }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('button', { name: '打开 / 创建论文库', exact: true }).or(page.getByRole('heading', { name: '论文库', exact: true }))).toBeVisible();
  if (await page.getByRole('button', { name: '打开 / 创建论文库' }).isVisible()) {
    await page.getByLabel('论文库目录', { exact: true }).fill(library);
    await page.getByRole('button', { name: '打开 / 创建论文库' }).click();
  }
  await expect(page.getByRole('heading', { name: '论文库', exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath('library-before-import.png'), fullPage: true });
  const imported = page.waitForResponse(response => response.url().endsWith('/papers/import') && response.request().method() === 'POST');
  await page.locator('input[type=file]').setInputFiles(fixture);
  const response = await imported;
  expect(response.ok()).toBeTruthy();
  const result = await response.json();
  expect(result.errors).toHaveLength(0);
  const paper = result.items[0] || result.duplicates[0];
  expect(paper.id).toBeTruthy();
  if (process.env.PAPERVAULT_E2E_REQUIRE_PARSE === '1' && ['failed', 'interrupted', 'cancelled'].includes(paper.status)) {
    await request.post(`${apiUrl}/papers/${paper.id}/reparse`, { headers });
  }
  await page.getByLabel('搜索论文', { exact: true }).fill(paper.filename);
  await expect(page.locator('.paper-item')).toHaveCount(1);
  await page.locator('.paper-primary').first().click();
  await expect(page.locator('.pdf-page canvas').first()).toBeVisible();
  await expect.poll(() => page.locator('.pdf-page canvas').first().evaluate((canvas: HTMLCanvasElement) => canvas.width)).toBeGreaterThan(0);
  await expect.poll(() => page.locator('.pdf-page .textLayer').first().innerText()).not.toBe('');
  await page.screenshot({ path: info.outputPath('pdf-reader.png'), fullPage: true });
  await page.getByRole('button', { name: '框选图片区域', exact: true }).click();
  const box = await page.locator('.pdf-page').first().boundingBox();
  expect(box).toBeTruthy();
  await page.mouse.move(box!.x + 80, box!.y + 120);
  await page.mouse.down();
  await page.mouse.move(box!.x + 280, box!.y + 260, { steps: 8 });
  await page.mouse.up();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByLabel('资源名称', { exact: true }).fill('E2E 手工裁剪');
  await page.getByLabel('Caption', { exact: true }).fill('深度学习 KV Cache 架构人工校对');
  await page.getByRole('button', { name: '保存 PNG', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: /^图片库/ }).click();
  await expect(page.getByRole('heading', { name: '图片库', exact: true })).toBeVisible();
  await page.getByLabel('搜索图片', { exact: true }).fill('架构');
  await expect(page.locator('.resource-card')).not.toHaveCount(0);
  await page.locator('.resource-card-image').first().click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.locator('.resource-preview img')).toBeVisible();
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: 'PNG', exact: true }).click();
  const file = await downloading;
  expect(file.suggestedFilename()).toMatch(/\.png$/);
  expect(await file.failure()).toBeNull();
  await file.saveAs(info.outputPath('manual-crop.png'));
  await page.getByRole('button', { name: '查看原文', exact: true }).click();
  await expect(page.locator('.pdf-highlight')).toBeVisible();
  await page.screenshot({ path: info.outputPath('pdf-located-crop.png'), fullPage: true });
  await page.keyboard.press('Control+k');
  await page.getByLabel('全局全文搜索', { exact: true }).fill('深度 KV');
  await expect(page.locator('.search-result')).not.toHaveCount(0);
  await expect(page.locator('.search-result mark').first()).toBeVisible();
  await page.screenshot({ path: info.outputPath('search-results.png'), fullPage: true });
  await page.reload();
  await expect(page.getByRole('heading', { name: '论文库', exact: true })).toBeVisible();
  await expect(page.locator('.paper-item')).not.toHaveCount(0);
  const resources = await (await request.get(`${apiUrl}/resources?paper_id=${paper.id}`, { headers })).json();
  expect(resources.items.some((r: { name: string }) => r.name === 'E2E 手工裁剪')).toBeTruthy();
  expect(errors).toEqual([]);
});

test('real Docling figures and table editing survive export', async ({ page, request }, info) => {
  test.skip(process.env.PAPERVAULT_E2E_REQUIRE_PARSE !== '1', 'Enable after installing CPU parser and local model bundle.');
  test.setTimeout(300000);
  const papers = await (await request.get(`${apiUrl}/papers`, { headers })).json();
  const paper = papers.items.find((p: { filename: string }) => p.filename === path.basename(fixture));
  expect(paper).toBeTruthy();
  await expect.poll(async () => (await (await request.get(`${apiUrl}/papers/${paper.id}`, { headers })).json()).status, { timeout: 240000 }).toMatch(/completed|partial|failed|interrupted/);
  const parsed = await (await request.get(`${apiUrl}/papers/${paper.id}`, { headers })).json();
  const jobs = await (await request.get(`${apiUrl}/jobs`, { headers })).json();
  expect(parsed.status, JSON.stringify(jobs)).toMatch(/completed|partial/);
  const resources = await (await request.get(`${apiUrl}/resources?paper_id=${paper.id}`, { headers })).json();
  expect(resources.items.some((r: { kind: string; name: string }) => r.kind === 'figure' && r.name !== 'E2E 手工裁剪')).toBeTruthy();
  expect(resources.items.some((r: { kind: string }) => r.kind === 'table')).toBeTruthy();
  await page.goto('/');
  await page.getByRole('button', { name: /^表格库/ }).click();
  await expect(page.locator('.resource-card')).not.toHaveCount(0);
  await page.locator('.resource-card-image').first().click();
  await expect(page.locator('.table-scroll table')).toBeVisible();
  await page.getByRole('button', { name: '编辑单元格 / 行列', exact: true }).click();
  await page.getByLabel('第 2 行第 1 列', { exact: true }).fill('TTFT 已人工验证');
  await page.getByRole('button', { name: '结束编辑', exact: true }).click();
  await page.getByRole('button', { name: '保存人工修改', exact: true }).click();
  await expect(page.locator('.table-scroll')).toContainText('TTFT 已人工验证');
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: 'CSV', exact: true }).click();
  const csv = await downloading;
  expect(csv.suggestedFilename()).toMatch(/\.csv$/);
  await csv.saveAs(info.outputPath('edited-table.csv'));
  await page.screenshot({ path: info.outputPath('table-editor.png'), fullPage: true });
  await page.getByRole('button', { name: '关闭对话框', exact: true }).click();
  await page.getByRole('button', { name: /^设置/ }).click();
  await expect(page.getByText('备份与恢复', { exact: true })).toBeVisible();
});

test('folders, notes, tags, theme and complete backup restore use the real API', async ({ page, request }, info) => {
  const name = `E2E 研究 ${Date.now()}`;
  await page.goto('/');
  await expect(page.locator('.paper-item')).not.toHaveCount(0);
  await page.getByRole('button', { name: '新建收藏夹', exact: true }).click();
  await page.getByLabel('收藏夹名称', { exact: true }).fill(name);
  await page.getByRole('button', { name: '创建收藏夹', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.locator('.paper-primary').first().click();
  await page.getByLabel('自定义标签', { exact: true }).fill('验证标签, 知识资产');
  await page.getByRole('textbox', { name: '个人备注', exact: true }).fill('真实端到端持久化备注');
  await page.getByRole('checkbox', { name, exact: true }).check();
  const saved = page.waitForResponse(response => /\/papers\/[^/]+$/.test(response.url()) && response.request().method() === 'PATCH');
  await page.getByRole('button', { name: '保存修改', exact: true }).click();
  expect((await saved).ok()).toBeTruthy();
  await page.getByRole('button', { name: '返回论文库', exact: true }).click();
  await page.getByRole('button', { name, exact: true }).click();
  await expect(page.locator('.paper-item')).not.toHaveCount(0);
  await page.getByRole('button', { name: /^设置/ }).click();
  await page.getByRole('button', { name: '深色', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.screenshot({ path: info.outputPath('settings-dark.png'), fullPage: true });
  await page.getByRole('button', { name: '浅色', exact: true }).click();
  await expect(page.getByRole('textbox', { name: /^备份文件路径/ })).toBeVisible();
  const backup = page.waitForResponse(response => response.url().endsWith('/backups') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '创建备份', exact: true }).click();
  const backupResponse = await backup;
  expect(backupResponse.ok()).toBeTruthy();
  const backupData = await backupResponse.json();
  expect(backupData.path).toMatch(/\.zip$/);
  await page.getByLabel('备份文件', { exact: true }).fill(backupData.path);
  const target = `${library}-restore-${Date.now()}`;
  await page.getByLabel('恢复到新的空目录', { exact: true }).fill(target);
  const restored = page.waitForResponse(response => response.url().endsWith('/backups/restore') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '校验备份并恢复', exact: true }).click();
  const restoreResponse = await restored;
  expect(restoreResponse.ok()).toBeTruthy();
  const libraryData = await (await request.get(`${apiUrl}/library`, { headers })).json();
  expect(path.normalize(libraryData.path)).toBe(path.normalize(target));
  await page.reload();
  await expect(page.locator('.paper-item')).not.toHaveCount(0);
  await page.locator('.paper-primary').first().click();
  await expect(page.getByRole('textbox', { name: '个人备注', exact: true })).toHaveValue('真实端到端持久化备注');
  await expect(page.getByLabel('自定义标签', { exact: true })).toHaveValue('验证标签, 知识资产');
});
